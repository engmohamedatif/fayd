function RuqyahPage() {
  const [copied, setCopied] = useState<string | null>(null);
  const [tab, setTab] = useState<"text" | "audio">("text");
  const copy = async (t: string, id: string) => {
    try {
      await navigator.clipboard.writeText(t);
      setCopied(id);
      setTimeout(() => setCopied(null), 1500);
    } catch { /* noop */ }
  };

  return (
    <div className="mx-auto max-w-3xl px-4 py-8 space-y-8">
      <header className="text-center space-y-2">
        <h1 className="text-3xl md:text-4xl font-extrabold">الرقية الشرعية</h1>
        <p className="text-muted-foreground text-sm">من كتاب الله وسنة رسوله ﷺ — تُقرأ على النفس أو المريض بيقين وإخلاص.</p>
      </header>

      <div className="flex justify-center gap-2">
        {(["text", "audio"] as const).map((t) => (
          <button
            key={t}
            onClick={() => setTab(t)}
            className={`rounded-full px-5 py-2 text-sm font-bold border border-border transition ${
              tab === t ? "bg-foreground text-background" : "md:hover:bg-muted"
            }`}
          >
            {t === "text" ? "مقروءة" : "مسموعة"}
          </button>
        ))}
      </div>

      {tab === "audio" && (
        <ArchiveBrowser
          topics={["الرقية الشرعية", "رقية العين والحسد", "رقية السحر", "الرقية الشرعية ياسر الدوسري", "رقية المس", "آيات الشفاء"].map(
            (q) => ({ label: q, query: q }),
          )}
          mediatype="audio"
        />
      )}

      {tab === "text" && SECTIONS.map((sec) => (
        <section key={sec.title} className="space-y-4">
          <h2 className="text-xl font-bold border-b border-border pb-2">{sec.title}</h2>
          {sec.intro && <p className="text-muted-foreground text-sm">{sec.intro}</p>}
          <div className="space-y-3">
            {sec.items.map((it, i) => {
              const id = `${sec.title}-${i}`;
              return (
                <article key={id} className="rounded-2xl border border-border bg-card p-5 space-y-2">
                  <div className="flex items-center justify-between">
                    <h3 className="font-bold">{it.title}</h3>
                    <button
                      onClick={() => copy(`${it.title}\n\n${it.text}\n\n[${it.source}]`, id)}
                      className="inline-flex items-center gap-1 text-xs rounded-full border border-border px-3 py-1 hover:bg-muted"
                    >
                      {copied === id ? <><Check className="h-3.5 w-3.5" /> تم النسخ</> : <><Copy className="h-3.5 w-3.5" /> نسخ</>}
                    </button>
                  </div>
                  <p className="font-quran text-xl leading-loose">{it.text}</p>
                  <div className="text-xs text-muted-foreground">— {it.source}</div>
                </article>
              );
            })}
          </div>
        </section>
      ))}
    </div>
  );
}
function StoriesPage() {
  const [selected, setSelected] = useState<Prophet | null>(null);
  const [q, setQ] = useState("");

  const filtered = useMemo(() => {
    const term = q.trim();
    if (!term) return PROPHETS;
    return PROPHETS.filter(
      (p) => p.name.includes(term) || p.title.includes(term) || (p.era ?? "").includes(term),
    );
  }, [q]);

  if (selected) {
    return (
      <div className="mx-auto max-w-3xl px-4 py-8 space-y-6">
        <button
          onClick={() => setSelected(null)}
          className="inline-flex items-center gap-1 text-sm text-muted-foreground hover:text-foreground"
        >
          <ChevronLeft className="h-4 w-4 rotate-180" /> رجوع للقصص
        </button>
        <header className="space-y-1">
          <h1 className="text-3xl md:text-4xl font-extrabold">
            {selected.name}{" "}
            <span className="text-base font-normal text-muted-foreground">— {selected.title}</span>
          </h1>
          {selected.era && (
            <p className="text-xs text-muted-foreground">{selected.era}</p>
          )}
        </header>
        <article className="space-y-8">
          {selected.sections.map((s, i) => (
            <section key={i} className="space-y-2">
              <h2 className="text-xl font-bold border-b border-border pb-2">{s.heading}</h2>
              <p className="leading-loose text-lg whitespace-pre-line font-arabic-quran">
                {s.body}
              </p>
            </section>
          ))}
        </article>
      </div>
    );
  }

  return (
    <div className="mx-auto max-w-4xl px-4 py-8 space-y-6">
      <header className="text-center space-y-2">
        <h1 className="text-3xl md:text-4xl font-extrabold">قصص الأنبياء والمرسلين</h1>
        <p className="text-muted-foreground text-sm">
          من آدم عليه السلام إلى خاتم النبيين محمد ﷺ — سرد مفصّل من القرآن الكريم والسنة النبوية.
        </p>
      </header>
      <div className="relative max-w-md mx-auto">
        <Search className="absolute right-3 top-1/2 -translate-y-1/2 h-4 w-4 text-muted-foreground" />
        <input
          value={q}
          onChange={(e) => setQ(e.target.value)}
          placeholder="ابحث عن نبي..."
          className="w-full rounded-xl border border-border bg-background py-2 pr-9 pl-3 text-sm outline-none focus:border-foreground"
        />
      </div>
      <div className="grid grid-cols-2 sm:grid-cols-3 md:grid-cols-4 gap-3">
        {filtered.map((p) => (
          <button
            key={p.name}
            onClick={() => setSelected(p)}
            className="group text-right rounded-2xl border border-border p-4 hover:bg-foreground hover:text-background transition"
          >
            <div className="font-bold text-lg">{p.name}</div>
            <div className="text-xs text-muted-foreground group-hover:text-background/80 mt-1">
              {p.title}
            </div>
          </button>
        ))}
      </div>
      <p className="text-center text-xs text-muted-foreground">
        {filtered.length} من {PROPHETS.length} نبيّاً
      </p>
    </div>
  );
}
